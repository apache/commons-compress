/*
 * Post-processes the CycloneDX SBOM generated by cyclonedx-maven-plugin:
 *
 * - upgrades it to CycloneDX 1.7, which the plugin does not support yet,
 * - marks all Maven dependencies as external (`isExternal`), since they are not bundled in our JAR,
 * - adds components from other ecosystems that are embedded in our Maven dependencies,
 *   e.g. native libraries bundled in JNI wrappers.
 *   Such components are invisible to Maven, so the plugin does not report them.
 * - registers itself and cyclonedx-core-java in `metadata.tools`.
 *
 * The script is idempotent: the SPDX plugin forks the lifecycle, so it may run twice.
 *
 * Runs with GMavenPlus, which binds `project`, `pluginArtifacts` and `log`.
 */

import java.security.MessageDigest

import org.cyclonedx.Version
import org.cyclonedx.generators.BomGeneratorFactory
import org.cyclonedx.model.Bom
import org.cyclonedx.model.Component
import org.cyclonedx.model.Dependency
import org.cyclonedx.model.ExternalReference
import org.cyclonedx.model.Hash
import org.cyclonedx.model.LicenseChoice
import org.cyclonedx.model.OrganizationalEntity
import org.cyclonedx.model.license.Acknowledgement
import org.cyclonedx.model.license.Expression
import org.cyclonedx.model.metadata.ToolInformation
import org.cyclonedx.parsers.JsonParser
import org.cyclonedx.parsers.Parser
import org.cyclonedx.parsers.XmlParser

final Version TARGET_VERSION = Version.VERSION_17
// Keep in sync with the GMavenPlus configuration in pom.xml
final String SCRIPT_PATH = 'src/conf/cyclonedx/add-embedded-components.groovy'

/*
 * Embedded components, keyed by the Maven groupId:artifactId of the embedding artifact.
 * `version` computes the version of the embedded component from the version of the Maven artifact.
 */
def embedded = [
    'com.github.luben:zstd-jni': [
        // zstd-jni versions are <zstd version>-<JNI revision>, e.g. 1.5.7-13
        version: { String v -> (v =~ /^(\d+\.\d+\.\d+)-\d+$/).with { it.matches() ? it.group(1) : null } },
        component: { String v ->
            new Component().with {
                type = Component.Type.LIBRARY
                // Vendor and product names as used in CVE records,
                // e.g. CVE-2021-24032, although the CNA records still say "Facebook".
                supplier = new OrganizationalEntity(name: 'Meta Platforms, Inc.', urls: ['https://github.com/meta'])
                manufacturer = new OrganizationalEntity(name: 'Meta Platforms, Inc.', urls: ['https://github.com/meta'])
                name = 'Zstandard'
                version = v
                description = 'Zstandard - Fast real-time compression algorithm (native library)'
                // The repository moved from facebook/zstd to meta/zstd; NVD still uses the old vendor name.
                purl = "pkg:github/meta/zstd@v${v}"
                bomRef = purl
                cpe = "cpe:2.3:a:facebook:zstandard:${v}:*:*:*:*:*:*:*"
                // zstd has no SPDX identifiers: it declares "BSD OR GPLv2" in prose (README, file headers).
                // The expression is concluded from those texts and matches the ClearlyDefined curation.
                licenses = new LicenseChoice(expression: new Expression(value: 'BSD-3-Clause OR GPL-2.0-only',
                        acknowledgement: Acknowledgement.CONCLUDED))
                addExternalReference(new ExternalReference(type: ExternalReference.Type.VCS, url: 'https://github.com/meta/zstd'))
                it
            }
        },
    ],
]

def baseName = "${project.build.directory}/${project.artifactId}-${project.version}-bom"
def jsonFile = new File("${baseName}.json")
def xmlFile = new File("${baseName}.xml")
if (!jsonFile.file) {
    fail("CycloneDX SBOM not found: ${jsonFile}")
}

Bom bom = new JsonParser().parse(jsonFile)

bom.components.each { Component parent ->
    parent.isExternal = true
    def spec = embedded["${parent.group}:${parent.name}"]
    if (spec == null) {
        return
    }
    def childVersion = spec.version(parent.version)
    if (childVersion == null) {
        fail("Cannot determine embedded component version from ${parent.group}:${parent.name}:${parent.version}")
    }
    Component child = spec.component(childVersion)
    if (parent.components?.any { it.bomRef == child.bomRef }) {
        return
    }
    parent.addComponent(child)
    // Also record it in the dependency graph, so tools that only follow `dependencies` see it.
    def parentDependency = bom.dependencies?.find { it.ref == parent.bomRef }
    if (parentDependency == null) {
        parentDependency = new Dependency(parent.bomRef)
        bom.addDependency(parentDependency)
    }
    parentDependency.addDependency(new Dependency(child.bomRef))
    bom.addDependency(new Dependency(child.bomRef))
    log.info("Added ${child.purl} as embedded in ${parent.purl}")
}

// Register the tools that modified the SBOM
if (bom.metadata.toolChoice == null) {
    bom.metadata.toolChoice = new ToolInformation(components: [])
}
def scriptFile = new File(project.basedir, SCRIPT_PATH)
def coreArtifact = pluginArtifacts.find { it.groupId == 'org.cyclonedx' && it.artifactId == 'cyclonedx-core-java' }
[
    new Component().with {
        type = Component.Type.APPLICATION
        group = project.groupId
        name = scriptFile.name
        version = project.version
        description = "Adds components embedded in Maven dependencies to the ${project.name} SBOM"
        hashes = [new Hash(Hash.Algorithm.SHA_256, MessageDigest.getInstance('SHA-256').digest(scriptFile.bytes).encodeHex().toString())]
        addExternalReference(new ExternalReference(type: ExternalReference.Type.VCS,
                url: "https://github.com/apache/commons-compress/blob/master/${SCRIPT_PATH}"))
        it
    },
    new Component().with {
        type = Component.Type.LIBRARY
        group = coreArtifact.groupId
        name = coreArtifact.artifactId
        version = coreArtifact.version
        description = 'CycloneDX core module'
        it
    },
].each { Component tool ->
    def tools = bom.metadata.toolChoice.components
    tools.removeIf { it.group == tool.group && it.name == tool.name }
    tools.add(tool)
}

bom.specVersion = TARGET_VERSION.versionString
jsonFile.setText(BomGeneratorFactory.createJson(TARGET_VERSION, bom).toJsonString(), 'UTF-8')
validate(new JsonParser(), jsonFile, TARGET_VERSION)
if (xmlFile.file) {
    xmlFile.setText(BomGeneratorFactory.createXml(TARGET_VERSION, bom).toXmlString(), 'UTF-8')
    validate(new XmlParser(), xmlFile, TARGET_VERSION)
}

void validate(Parser parser, File file, Version version) {
    def errors = parser.validate(file, version)
    if (errors) {
        fail("Invalid CycloneDX ${version.versionString} SBOM ${file}:\n" + errors*.message.join('\n'))
    }
}

void fail(String message) {
    throw new org.apache.maven.plugin.MojoFailureException(message)
}
